# PDF  (English only — see the module docstring)
# ═══════════════════════════════════════════════════════════════════════════

def to_pdf(explanation: dict) -> bytes:
    """
    Render an English explanation to PDF bytes via ReportLab.

    Raises
    ------
    ValueError
        If the explanation is not English.  Devanagari needs OpenType shaping
        that ReportLab cannot do; callers should offer `to_html()` instead.
    """
    lang = explanation.get("lang", "en")
    if lang != "en":
        raise ValueError(_PDF_UNSUPPORTED["hi"])

    from reportlab.lib.enums import TA_LEFT
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import (ListFlowable, ListItem, Paragraph,
                                    SimpleDocTemplate, Spacer)

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer, pagesize=A4,
        leftMargin=22 * mm, rightMargin=22 * mm,
        topMargin=20 * mm, bottomMargin=20 * mm,
        title=_TITLES["en"], author="Causal Financial Decision Intelligence System",
    )

    base = getSampleStyleSheet()
    styles = {
        "title": ParagraphStyle("t", parent=base["Title"], fontSize=20, spaceAfter=4,
                                alignment=TA_LEFT, textColor="#12263f"),
        "sub"  : ParagraphStyle("s", parent=base["Normal"], fontSize=10.5,
                                textColor="#555", spaceAfter=16),
        "h2"   : ParagraphStyle("h", parent=base["Heading2"], fontSize=12.5,
                                spaceBefore=16, spaceAfter=6, textColor="#23395d"),
        "body" : ParagraphStyle("b", parent=base["Normal"], fontSize=10.5,
                                leading=16, spaceAfter=8),
        "foot" : ParagraphStyle("f", parent=base["Normal"], fontSize=8.5,
                                textColor="#777", spaceBefore=20),
    }

    story = [Paragraph(_TITLES["en"], styles["title"]),
             Paragraph(_esc_pdf(explanation.get("recommendation", "")), styles["sub"])]

    for section in explanation.get("sections", []):
        story.append(Paragraph(_esc_pdf(section["title"]), styles["h2"]))
        for block in section["text"].split("\n\n"):
            lines = [ln.strip() for ln in block.strip().split("\n") if ln.strip()]
            if not lines:
                continue
            if all(ln.startswith("|") for ln in lines):
                story.append(_pdf_table(lines, styles["body"]))
            elif all(ln.startswith("- ") for ln in lines):
                story.append(ListFlowable(
                    [ListItem(Paragraph(_esc_pdf(ln[2:]), styles["body"])) for ln in lines],
                    bulletType="bullet", leftIndent=12,
                ))
            else:
                story.append(Paragraph(_esc_pdf(" ".join(lines)), styles["body"]))

    story.append(Spacer(1, 6))
    story.append(Paragraph(_esc_pdf(_FOOTERS["en"]), styles["foot"]))

    doc.build(story)
    return buffer.getvalue()


def _pdf_table(lines: list[str], body_style):
    """
    Render a Markdown table as a ReportLab Table.

    The year-by-year table is the part of the explanation a reader is most
    likely to study line by line, so it has to survive the trip to PDF as a
    table rather than collapsing into a paragraph of pipes.
    """
    from reportlab.lib import colors
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, Table, TableStyle

    rows = [_split_row(ln) for ln in lines if not _is_separator(ln)]
    if not rows:
        return Paragraph("", body_style)

    cell = ParagraphStyle("cell", parent=body_style, fontSize=9, leading=12, spaceAfter=0)
    head = ParagraphStyle("head", parent=cell, fontName="Helvetica-Bold", textColor=colors.HexColor("#23395d"))

    data = [[Paragraph(_esc_pdf(c), head) for c in rows[0]]]
    data += [[Paragraph(_esc_pdf(c), cell) for c in row] for row in rows[1:]]

    table = Table(data, hAlign="LEFT", colWidths=[24 * mm] + [38 * mm] * (len(rows[0]) - 1))
    table.setStyle(TableStyle([
        ("BACKGROUND",   (0, 0), (-1, 0), colors.HexColor("#f6f8fb")),
        ("LINEBELOW",    (0, 0), (-1, 0), 0.8, colors.HexColor("#dde3ec")),
        ("LINEBELOW",    (0, 1), (-1, -2), 0.25, colors.HexColor("#ececec")),
        ("VALIGN",       (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING",  (0, 0), (-1, -1), 5),
        ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING",   (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING",(0, 0), (-1, -1), 3),
    ]))
    return table


def _esc_pdf(text: str) -> str:
    """
    Escape for ReportLab's mini-HTML, then restore the **bold** markers the
    templates use.  The rupee sign is spelled out because the built-in Type 1
    fonts have no ₹ glyph and would silently print a black box.
    """
    out = (text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))
    out = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", out, flags=re.DOTALL)
    out = out.replace("₹", "Rs.").replace("—", "-").replace("·", "-")
    return out



"""
═══════════════════════════════════════════════════════════════════════════
 explanation_report.py — downloadable GAP 3 explanation reports
═══════════════════════════════════════════════════════════════════════════

Turns an explanation dict from `explainer.py` into something the user can
keep, print, or show to an advisor.

Three formats:

    markdown  — plain text, always works, both languages
    html      — styled and print-ready, both languages   ← recommended
    pdf       — ReportLab, ENGLISH ONLY (see the note below)

Why HTML is the recommended format, not PDF
-------------------------------------------
ReportLab has no OpenType text shaper.  Devanagari needs one: in "कि" the
matra ि is stored after the consonant but must be *drawn before* it, and
conjuncts like क्ष must be composed.  Without shaping, ReportLab draws the
codepoints in storage order, so a Hindi PDF comes out subtly wrong and, in
places, unreadable.  Rather than ship broken Hindi typography, the HTML
report is styled for printing — any browser shapes Devanagari correctly, and
"Print → Save as PDF" produces a proper PDF in either language.

So `to_pdf()` serves English, and Hindi is routed to HTML.  `available_formats()`
tells callers which is which so the UI can offer only what actually works.

Public API
----------
    to_markdown(explanation)        -> str
    to_html(explanation)            -> str
    to_pdf(explanation)             -> bytes
    available_formats(lang)         -> list[str]
    filename_for(explanation, fmt)  -> str
"""


def _inline_md(text: str) -> str:
    """Convert the small subset of Markdown the templates use into HTML."""
    out = html.escape(text)
    out = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", out, flags=re.DOTALL)
    return out


def _split_row(line: str) -> list[str]:
    """Split a Markdown table row into its cells."""
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def _is_separator(line: str) -> bool:
    """The `|---|---|` line under a Markdown table header."""
    return bool(re.fullmatch(r"\|[\s:|-]+\|", line.strip()))


def _table_to_html(lines: list[str]) -> str:
    """Render a Markdown table as real HTML, wrapped so it scrolls on mobile."""
    rows = [_split_row(ln) for ln in lines if not _is_separator(ln)]
    if not rows:
        return ""
    header, body = rows[0], rows[1:]

    head_html = "".join(f"<th>{_inline_md(c)}</th>" for c in header)
    body_html = "".join(
        "<tr>" + "".join(f"<td>{_inline_md(c)}</td>" for c in row) + "</tr>"
        for row in body
    )
    return (f'<div class="table-wrap"><table><thead><tr>{head_html}</tr></thead>'
            f"<tbody>{body_html}</tbody></table></div>")


def _blocks_to_html(text: str) -> str:
    """
    Render a section body: Markdown tables become real tables, bullet lists
    become <ul>, and everything else becomes paragraphs.
    """
    parts: list[str] = []
    for block in text.split("\n\n"):
        lines = [ln.strip() for ln in block.strip().split("\n") if ln.strip()]
        if not lines:
            continue
        if all(ln.startswith("|") for ln in lines):
            parts.append(_table_to_html(lines))
        elif all(ln.startswith("- ") for ln in lines):
            items = "".join(f"<li>{_inline_md(ln[2:])}</li>" for ln in lines)
            parts.append(f"<ul>{items}</ul>")
        else:
            parts.append(f"<p>{_inline_md(' '.join(lines))}</p>")
    return "\n".join(parts)


def to_html(explanation: dict) -> str:
    """
    Self-contained, print-ready HTML.  No external assets, so it opens
    correctly from a downloads folder with no network.
    """
    lang  = explanation.get("lang", "en")
    title = _TITLES.get(lang, _TITLES["en"])

    badge_cls  = "ok" if not explanation.get("is_biased") or explanation.get("resisted") else "warn"
    badge_text = T.BIAS_PLAIN[lang].get(explanation.get("bias_type", "unknown"), "")

    body = [f"<h1>{html.escape(title)}</h1>",
            f'<p class="sub">{html.escape(explanation.get("recommendation", ""))}</p>',
            f'<span class="badge {badge_cls}">{html.escape(badge_text)}</span>']

    for section in explanation.get("sections", []):
        body.append(f"<h2>{html.escape(section['title'])}</h2>")
        body.append(_blocks_to_html(section["text"]))

    body.append(f"<footer>{html.escape(_FOOTERS.get(lang, _FOOTERS['en']))}</footer>")

    return (
        "<!doctype html>\n"
        f'<html lang="{lang}"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width, initial-scale=1">'
        f"<title>{html.escape(title)}</title><style>{_CSS}</style></head>"
        f"<body>{''.join(body)}</body></html>"
    )



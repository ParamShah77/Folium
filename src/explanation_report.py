def available_formats(lang: str = "en") -> list[str]:
    """Formats that render correctly for this language."""
    return ["md", "html", "pdf"] if lang == "en" else ["md", "html"]


def filename_for(explanation: dict, fmt: str) -> str:
    """A stable, descriptive download filename."""
    lang = explanation.get("lang", "en")
    bias = explanation.get("bias_type", "decision")
    return f"decision_explained_{bias}_{lang}.{fmt}"



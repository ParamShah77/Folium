def _row_dicts(r: Any, regime: str | None = None) -> tuple[dict, dict, dict]:
    s = {
        "unrealized_gl": float(r.unrealized_gl),
        "nifty_1m_return": float(r.nifty_1m_return),
        "vix": float(r.vix),
        "regime": regime if regime is not None else r.regime,
    }
    inv = {
        "monthly_income": float(r.monthly_income),
        "monthly_emi": float(r.monthly_emi),
        "rent_paid": float(r.rent_paid),
        "education_monthly": float(r.education_monthly),
        "has_emergency_fund": int(r.has_emergency_fund),
        "investment_horizon": int(r.investment_horizon),
        "years_investing": float(r.years_investing),
        "latent_loss_aversion": float(r.latent_loss_aversion),
        "latent_herd": float(r.latent_herd),
        "latent_disposition": float(r.latent_disposition),
    }
    pf = {"rent_received": float(r.rent_received), "position_share": float(r.position_share)}
    # v4.1: is the sale forced by money? Recomputed (not read from the stored
    # flag) so interventions on the fund or the payments flow through.
    surplus = inv["monthly_income"] + pf["rent_received"] - (inv["monthly_emi"] + inv["rent_paid"] + inv["education_monthly"])
    inv["needs_cash"] = D.needs_cash(surplus, inv["has_emergency_fund"], int(getattr(r, "latent_cash_shock", 0)),
                                     float(getattr(r, "latent_shock_u", 1.0)))
    return s, inv, pf


def rational_action_distribution(s: dict, inv: dict, pf: dict) -> dict[str, float]:
    """The rational motive's action, as probabilities (dataset_v4.rational_action draws one)."""
    surplus = inv["monthly_income"] + pf["rent_received"] - (inv["monthly_emi"] + inv["rent_paid"] + inv["education_monthly"])
    surplus_ratio = surplus / inv["monthly_income"]
    out = {a: 0.0 for a in ACTIONS}
    if inv["needs_cash"]:
        out["sell"] = 1.0
        return out
    if pf["position_share"] > 0.35:
        out["sell"] = 1.0
        return out
    if inv["investment_horizon"] <= 3 and s["unrealized_gl"] > 0:
        out["sell"] = 1.0
        return out
    if (s["nifty_1m_return"] <= -0.06 and inv["has_emergency_fund"] and surplus_ratio > 0.25
            and inv["investment_horizon"] >= 10 and pf["position_share"] < 0.25):
        out["buy_more"] = 1.0
        return out
    left = 1.0
    if surplus_ratio > 0.35 and inv["investment_horizon"] >= 8 and pf["position_share"] < 0.12:
        out["buy_more"] += left * 0.35
        left *= 0.65
    if s["unrealized_gl"] <= -0.12:
        out["sell"] += left * 0.30
        left *= 0.70
    if (s["unrealized_gl"] <= -0.10 and surplus_ratio > 0.30 and inv["has_emergency_fund"]
            and inv["investment_horizon"] >= 10 and pf["position_share"] < 0.15):
        out["buy_more"] += left * 0.30
        left *= 0.70
    out["hold"] += left
    return out


def motive_weights(s: dict, inv: dict, pf: dict) -> list[tuple[D.Motive | None, float]]:
    """Competing motives and weights, rational first (``None`` stands for rational)."""
    out: list[tuple[D.Motive | None, float]] = [
        (None, 0.7 + 0.025 * inv["years_investing"] + 0.25 * inv["has_emergency_fund"]
         + (D.NEEDS_CASH_WEIGHT if inv["needs_cash"] else 0.0))
    ]
    for m in D.applicable_bias_motives(s):
        trait = inv[D._TRAIT[m.label]]
        intensity = 1.0
        if m.name == "loss_aversion_panic":
            intensity = 1.0 + min(abs(s["unrealized_gl"]) * 3, 1.5)
        elif m.name == "loss_aversion_refusal":
            intensity = 1.0 + min((abs(s["unrealized_gl"]) - 0.25) * 3, 1.0)
        elif m.name == "disposition_sell_winner":
            intensity = 1.0 + min((s["unrealized_gl"] - D.EARLY_WIN) * 2, 1.0)
        elif m.name == "disposition_hold_loser":
            intensity = 1.4 + min(abs(s["unrealized_gl"]) * 2, 0.6)
        elif m.name == "herd_sell_fear":
            intensity = 1.0 + D.crowd_ratio_from_vix(s["vix"])
        elif m.name == "herd_buy_frenzy":
            intensity = 1.0 + min(s["nifty_1m_return"] * 6, 1.0)
        out.append((m, D._STRENGTH[m.label] * trait ** 1.5 * intensity))
    return out


def action_probabilities(s: dict, inv: dict, pf: dict) -> np.ndarray:
    """Exact P(sell), P(hold), P(buy more) for one case."""
    weights = motive_weights(s, inv, pf)
    total = sum(w for _, w in weights)
    rational = rational_action_distribution(s, inv, pf)
    p = np.zeros(3)
    for motive, w in weights:
        if motive is None:
            p += (w / total) * np.array([rational[a] for a in ACTIONS])
        else:
            p[ACTIONS.index(motive.action)] += w / total
    return p


def true_probabilities(df: pd.DataFrame) -> np.ndarray:
    """(n, 3) exact action probabilities for every row (columns may be intervened on)."""
    out = np.empty((len(df), 3))
    recompute = "drawdown_52w" in df.columns and df.attrs.get("market_changed", False)
    for i, r in enumerate(df.itertuples(index=False)):
        regime = D._regime(r.nifty_1m_return, r.vix, r.drawdown_52w) if recompute else None
        out[i] = action_probabilities(*_row_dicts(r, regime))
    return out


def consistency_with_stored_data(df: pd.DataFrame) -> dict[str, float]:
    """Do the weights reproduce each case's stored motive_share? (They must, exactly.)"""
    errors = []
    for r in df.itertuples(index=False):
        s, inv, pf = _row_dicts(r)
        weights = motive_weights(s, inv, pf)
        total = sum(w for _, w in weights)
        if r.motive.startswith("rational"):
            share = weights[0][1] / total
        else:
            share = next(w for m, w in weights if m is not None and m.name == r.motive) / total
        errors.append(abs(round(share, 4) - r.motive_share))
    errors = np.array(errors)
    return {"cases": int(len(errors)), "max_abs_error": float(errors.max()),
            "share_exact_to_4dp": float((errors < 1e-6).mean())}



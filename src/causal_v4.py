#: What a study would observe: everything except the motive that won.
OBSERVED = [
    "latent_loss_aversion", "latent_herd", "latent_disposition",
    "age", "years_investing", "risk_tolerance", "investment_horizon",
    "surplus_ratio", "has_emergency_fund", "position_share", "gold_share", "equity_share",
    "latent_cash_shock",   # v4.1: observed in a study (like the tendencies), never a model input
    "unrealized_gl", "holding_period_months", "nifty_1m_return", "vix", "nifty_volatility_30d", "drawdown_52w",
]


def prepare(df: pd.DataFrame) -> pd.DataFrame:
    out = df.copy()
    out["surplus_ratio"] = (out.monthly_income + out.rent_received - out.monthly_outflow) / out.monthly_income
    for a in ACTIONS:
        out[f"is_{a}"] = (out.action == a).astype(int)
    return out


def _refresh_derived(df: pd.DataFrame) -> pd.DataFrame:
    df = df.copy()
    df["surplus_ratio"] = (df.monthly_income + df.rent_received - df.monthly_outflow) / df.monthly_income
    return df


class GComputation:
    """S-learner: P(action | everything observed), queried under interventions."""

    def __init__(self, df: pd.DataFrame, seed: int = 0):
        from sklearn.ensemble import HistGradientBoostingClassifier

        self.model = HistGradientBoostingClassifier(max_iter=400, learning_rate=0.06, max_leaf_nodes=31,
                                                    l2_regularization=1.0, random_state=seed)
        self.model.fit(df[OBSERVED], df.action.map({a: i for i, a in enumerate(ACTIONS)}))

    def probabilities(self, df: pd.DataFrame) -> np.ndarray:
        p = self.model.predict_proba(_refresh_derived(df)[OBSERVED])
        out = np.zeros((len(df), 3))
        out[:, self.model.classes_] = p
        return out


def dowhy_effect(df: pd.DataFrame, column: str, outcome: str, refute: bool = True) -> dict[str, Any]:
    """Backdoor adjustment (linear probability model) with three refutation tests.

    The graph mirrors the generator: observed traits and circumstances point
    to the action; profile variables also point to the traits.
    """
    import logging

    from dowhy import CausalModel

    logging.getLogger("dowhy").setLevel(logging.ERROR)
    cols = [c for c in OBSERVED if c in df.columns]
    data = df[cols + [outcome]].copy()
    profile = ["age", "years_investing", "risk_tolerance", "surplus_ratio", "has_emergency_fund"]
    traits = ["latent_loss_aversion", "latent_herd", "latent_disposition"]
    edges = [(c, outcome) for c in cols]
    edges += [(p, t) for p in profile for t in traits]
    edges += [("age", "years_investing"), ("age", "investment_horizon"), ("years_investing", "risk_tolerance"),
              ("risk_tolerance", "equity_share"), ("risk_tolerance", "gold_share"),
              ("nifty_1m_return", "unrealized_gl"), ("holding_period_months", "unrealized_gl"),
              ("drawdown_52w", "unrealized_gl"), ("vix", "nifty_volatility_30d")]
    gml = "graph [directed 1\n" + "".join(f'node [id "{n}" label "{n}"]\n' for n in cols + [outcome])
    gml += "".join(f'edge [source "{u}" target "{v}"]\n' for u, v in edges) + "]"
    model = CausalModel(data=data, treatment=column, outcome=outcome, graph=gml)
    # Maximal adjustment: every observed non-descendant of the treatment. The
    # default search enumerates adjustment sets and is exponential in the
    # number of variables; for this graph the maximal set is a valid one.
    ident = model.identify_effect(method_name="maximal-adjustment", proceed_when_unidentifiable=True)
    # Average effect only. By default DoWhy also estimates a separate effect for
    # every combination of the other parents of the outcome, which here means
    # one per row — minutes per call and nothing we use.
    est = model.estimate_effect(ident, method_name="backdoor.linear_regression",
                                method_params={"init_params": {"need_conditional_estimates": False}})
    out: dict[str, Any] = {"effect_per_unit": float(est.value)}
    if refute:
        checks = {}
        for name, kw in (("placebo treatment", dict(method_name="placebo_treatment_refuter", placebo_type="permute", num_simulations=10)),
                         ("random common cause", dict(method_name="random_common_cause", num_simulations=10)),
                         ("data subset", dict(method_name="data_subset_refuter", subset_fraction=0.8, num_simulations=10))):
            r = model.refute_estimate(ident, est, random_seed=1, **kw)
            p = r.refutation_result.get("p_value") if isinstance(r.refutation_result, dict) else None
            checks[name] = {"new_effect": float(r.new_effect), "p_value": None if p is None else float(p)}
        base = abs(out["effect_per_unit"])
        out["refutations"] = checks
        out["refutation_passed"] = bool(
            abs(checks["placebo treatment"]["new_effect"]) < 0.25 * base + 1e-4
            and abs(checks["random common cause"]["new_effect"] - out["effect_per_unit"]) < 0.1 * base + 1e-4
            and abs(checks["data subset"]["new_effect"] - out["effect_per_unit"]) < 0.25 * base + 1e-4
        )
    return out



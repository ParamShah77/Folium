Do = Callable[[pd.DataFrame], pd.DataFrame]


def do(**changes: Callable[[pd.DataFrame], Any] | float) -> Do:
    """A do-operation: set columns to a value or to a function of the frame."""
    def apply(df: pd.DataFrame) -> pd.DataFrame:
        out = df.copy()
        for col, v in changes.items():
            out[col] = v(out) if callable(v) else v
        if {"vix", "nifty_1m_return"} & set(changes):
            out.attrs["market_changed"] = True
        return out
    return apply



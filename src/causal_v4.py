"""
═══════════════════════════════════════════════════════════════════════════
 causal_v4.py — cause and effect on dataset v4, checked against the truth (Phase A4)
═══════════════════════════════════════════════════════════════════════════
What the old analysis (src/causal_inference.py) did, and why it is replaced
--------------------------------------------------------------------------
It estimated linear effects on the v1-v3 synthetic data with a hand-drawn
graph containing arrows that cannot be causal (a personality trait "causing"
the crowd's selling, or the size of a loss), measured only effects on
*selling*, and computed every "what helps" figure from a hard-coded 70%
starting chance of selling.

What this module does
---------------------
1. **Knows the truth.** Dataset v4 was generated by explicit rules
   (src/dataset_v4.py). :func:`action_probabilities` reproduces, exactly, the
   probability each case ended in sell / hold / buy more — verified against
   the stored ``motive_share`` of all 20,000 cases. Changing one input and
   recomputing gives the *true* causal effect of that input: a do-operation on
   the real mechanism, with no estimation error.
2. **Estimates the way a real study would** — from the data alone, without
   the rules — with two methods:
     * DoWhy backdoor adjustment (linear probability model) on a graph that
       mirrors the generator, with three refutation tests;
     * g-computation: a gradient-boosted model of the action given everything
       observed, queried under the intervention (S-learner).
   Both are compared with the truth. ``gold_share`` has no causal path to the
   decision at all, so it is a built-in negative control: a sound estimator
   must find ~0.
3. **Answers per situation and action.** Loss aversion makes people panic-
   sell in a falling market *and* hold deep losers; herd behaviour makes them
   sell into fear *and* buy into a rally. For each (pattern, action) the
   module reports how likely that action is in that situation, and how much a
   habit that weakens the tendency changes it.

Habits are modelled as halving the relevant tendency. How much a real habit
changes a tendency is not something this data can measure; the assumption
is stated wherever the numbers appear.

Output: results/causal_v4.json (read by backend/core/explainer.py).
"""

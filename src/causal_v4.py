def _delta(df: pd.DataFrame, intervention: Do, prob: Callable[[pd.DataFrame], np.ndarray],
           mask: np.ndarray | None = None) -> np.ndarray:
    sub = df if mask is None else df[mask]
    return prob(intervention(sub)).mean(axis=0) - prob(sub).mean(axis=0)


def run(df: pd.DataFrame | None = None, refute: bool = True, verbose: bool = True) -> dict[str, Any]:
    t0 = time.time()
    raw = pd.read_csv(D.DATASET_CSV) if df is None else df
    data = prepare(raw)
    log = print if verbose else (lambda *a, **k: None)

    consistency = consistency_with_stored_data(data)
    log(f"mechanism reproduces stored motive shares: max error {consistency['max_abs_error']:.2e}")

    truth = lambda d: true_probabilities(d)            # noqa: E731
    g = GComputation(data)
    est = g.probabilities

    # ── Population effects on each action ────────────────────────────────
    effects: dict[str, Any] = {}
    for key, t in TREATMENTS.items():
        mask = t["among"](data).to_numpy() if "among" in t else None
        d_true = _delta(data, t["do"], truth, mask)
        d_g = _delta(data, t["do"], est, mask)
        entry = {
            "label": t["label"], "unit": t["unit"], "column": t["column"],
            "negative_control": bool(t.get("negative_control", False)),
            "true": {a: round(float(v), 4) for a, v in zip(ACTIONS, d_true)},
            "g_computation": {a: round(float(v), 4) for a, v in zip(ACTIONS, d_g)},
        }
        # DoWhy on P(sell): per unit of the column (whole sample, so a binary
        # treatment varies), scaled to the same change as the intervention.
        if refute:
            dw = dowhy_effect(data, t["column"], "is_sell")
            base = data if mask is None else data[mask]
            change = float(_refresh_derived(t["do"](base))[t["column"]].mean() - base[t["column"]].mean())
            entry["dowhy_linear"] = {"sell": round(dw["effect_per_unit"] * change, 4),
                                     "refutation_passed": dw["refutation_passed"],
                                     "refutations": dw["refutations"]}
        # Legacy scalar the explanation engine ranks drivers by: effect on selling.
        entry["causal_effect"] = entry["g_computation"]["sell"]
        entry["refutation_passed"] = entry.get("dowhy_linear", {}).get("refutation_passed")
        entry["method"] = "g-computation (gradient boosting), checked against the true mechanism"
        effects[key] = entry
        log(f"  {key:22} true sell {d_true[0]:+.4f}  g-comp {d_g[0]:+.4f}"
            + (f"  dowhy {entry['dowhy_linear']['sell']:+.4f} refuted-ok={entry['dowhy_linear']['refutation_passed']}" if refute else ""))

    # ── Situations: how likely the action is there, and what habits change ─
    situations: dict[str, Any] = {}
    for (bias, action), spec in SITUATIONS.items():
        mask = situation_mask(data, spec["motive"])
        k = ACTIONS.index(action)
        sub = data[mask]
        base_true = float(truth(sub)[:, k].mean())
        base_obs = float(sub[f"is_{action}"].mean())
        t = TREATMENTS[spec["trait"]]
        trait_true = float(_delta(data, t["do"], truth, mask)[k])
        trait_g = float(_delta(data, t["do"], est, mask)[k])
        entry: dict[str, Any] = {
            "situation": spec["situation"], "cases": int(mask.sum()),
            "share_taking_action_observed": round(base_obs, 4),
            "share_taking_action_true": round(base_true, 4),
            "tendency_effect": {"unit": t["unit"], "true": round(trait_true, 4), "g_computation": round(trait_g, 4)},
            "habits": {},
        }
        if refute:
            dw = dowhy_effect(sub, t["column"], f"is_{action}")
            entry["tendency_effect"]["dowhy_linear"] = round(dw["effect_per_unit"] * 0.1, 4)
            entry["tendency_effect"]["refutation_passed"] = dw["refutation_passed"]
            entry["tendency_effect"]["refutations"] = dw["refutations"]
        for h in spec["habits"]:
            hd = HABITS[h]
            new_true = float(truth(hd["do"](sub))[:, k].mean())
            new_g = float(est(hd["do"](sub))[:, k].mean())
            base_g = float(est(sub)[:, k].mean())
            entry["habits"][h] = {
                "description": hd["description"],
                "before_true": round(base_true, 4), "after_true": round(new_true, 4),
                "before_estimated": round(base_g, 4), "after_estimated": round(new_g, 4),
            }
        situations[f"{bias}:{action}"] = entry
        best = min(entry["habits"].items(), key=lambda kv: kv[1]["after_estimated"] if kv[0] != "combined" else 9)
        log(f"  {bias}:{action:9} n={entry['cases']:5} {action} {base_obs:.2f}; tendency +0.1 -> true {trait_true:+.3f} g {trait_g:+.3f}; "
            f"{best[0]} {best[1]['before_estimated']:.2f}->{best[1]['after_estimated']:.2f} (true {best[1]['before_true']:.2f}->{best[1]['after_true']:.2f})")

    # ── How well the estimates match the truth ───────────────────────────
    pairs = [(e["true"]["sell"], e["g_computation"]["sell"]) for e in effects.values()]
    pairs += [(e["true"][a], e["g_computation"][a]) for e in effects.values() for a in ("hold", "buy_more")]
    pairs += [(s["tendency_effect"]["true"], s["tendency_effect"]["g_computation"]) for s in situations.values()]
    tr, gc = np.array(pairs).T
    signif = np.abs(tr) >= 0.005
    accuracy = {
        "g_computation_mean_abs_error": round(float(np.abs(tr - gc).mean()), 4),
        "g_computation_sign_agreement": round(float((np.sign(tr[signif]) == np.sign(gc[signif])).mean()), 4),
        "effects_compared": int(len(tr)),
    }
    if refute:
        dw_pairs = np.array([(e["true"]["sell"], e["dowhy_linear"]["sell"]) for e in effects.values()])
        accuracy["dowhy_linear_mean_abs_error_sell"] = round(float(np.abs(dw_pairs[:, 0] - dw_pairs[:, 1]).mean()), 4)
        accuracy["g_computation_mean_abs_error_sell"] = round(float(np.abs(
            np.array([e["true"]["sell"] - e["g_computation"]["sell"] for e in effects.values()])).mean()), 4)
        accuracy["refutations_passed"] = int(sum(bool(e["dowhy_linear"]["refutation_passed"]) for e in effects.values()))
        accuracy["refutations_total"] = len(effects)

    result = {
        "version": "v4",
        "generated": time.strftime("%Y-%m-%d"),
        "dataset": "data/v4/decisions_v4.csv",
        "mechanism_check": consistency,
        "causal_effects": effects,
        "situations": situations,
        "interventions": {k: {"description": v["description"]} for k, v in HABITS.items()},
        "accuracy": accuracy,
        "assumptions": {
            "habits": "a habit is modelled as halving the tendency it targets; 'not watching the crowd' as market fear no higher than VIX 15",
            "estimates_shown_in_app": "g-computation from data alone; the true values are for checking",
        },
        "runtime_seconds": round(time.time() - t0, 1),
    }
    return result


def save(result: dict[str, Any], path: str = RESULTS_PATH) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(result, f, indent=2, default=lambda o: o.item() if hasattr(o, "item") else str(o))


def load_results(path: str = RESULTS_PATH) -> dict[str, Any]:
    if not os.path.exists(path):
        raise FileNotFoundError(f"{path} — run: python -m src.causal_v4")
    with open(path, encoding="utf-8") as f:
        return json.load(f)


